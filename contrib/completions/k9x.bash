    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="k9x"
                ;;
            k9x,completions)
                cmd="k9x__subcmd__completions"
                ;;
            k9x,cordon)
                cmd="k9x__subcmd__cordon"
                ;;
            k9x,ctx)
                cmd="k9x__subcmd__ctx"
                ;;
            k9x,decode)
                cmd="k9x__subcmd__decode"
                ;;
